// carbonImpactService.ts
// Provides utilities for calculating CO2 savings and
// carbon credits, and for recording recycling transactions
// in Firestore.

import {
  getFirestore,
  collection,
  doc,
  addDoc,
  updateDoc,
  serverTimestamp,
  increment,
  getDoc,
} from 'firebase/firestore';

// mapping of waste types to CO2 savings per kilogram
export const CO2_SAVINGS_MAP: Record<string, number> = {
  plastic: 2,
  paper: 1,
  metal: 9,
  glass: 0.5,
  organic: 0.3,
};

// calculate how many kilograms of CO2 are saved for a given
// waste type and weight in kilograms.  If the waste type is
// not recognised, returns 0.
export function calculateCO2Saved(
  wasteType: string,
  weightKg: number,
): number {
  if (!wasteType || weightKg <= 0) {
    return 0;
  }
  const normalised = wasteType.toLowerCase();
  const perKg = CO2_SAVINGS_MAP[normalised] ?? 0;
  return perKg * weightKg;
}

// convert CO2 saved (in kg) into carbon credits according to
// the rule 100kg CO2 = 1 credit.  Result is a floating point
// number; consumers can round if desired.
export function convertToCarbonCredits(co2Saved: number): number {
  if (co2Saved <= 0) {
    return 0;
  }
  return co2Saved / 100;
}

// Firestore references
const db = getFirestore();
const usersCol = collection(db, 'users');
const txCol = collection(db, 'recyclingTransactions');

// record a recycling transaction and update the corresponding
// user document atomically.
export async function recordRecyclingTransaction(
  userId: string,
  wasteType: string,
  weightKg: number,
): Promise<void> {
  if (!userId) {
    throw new Error('userId is required');
  }
  if (!wasteType) {
    throw new Error('wasteType is required');
  }
  if (weightKg <= 0) {
    throw new Error('weightKg must be positive');
  }

  // compute derived values
  const co2Saved = calculateCO2Saved(wasteType, weightKg);
  const carbonCreditsEarned = convertToCarbonCredits(co2Saved);

  try {
    // create a new transaction document with autogenerated ID
    const txRef = await addDoc(txCol, {
      userId,
      wasteType,
      weightKg,
      co2Saved,
      carbonCreditsEarned,
      createdAt: serverTimestamp(),
    });

    // update the user summary document
    const userRef = doc(usersCol, userId);
    // ensure the document exists by reading once; if it does not,
    // create it with zeroed fields so that the increments work later.
    const userSnap = await getDoc(userRef);
    if (!userSnap.exists()) {
      await updateDoc(userRef, {
        totalWasteRecycled: 0,
        totalCO2Saved: 0,
        carbonCredits: 0,
      }).catch(() => {
        // if update fails because doc doesn't exist, use set
        return;
      });
    }

    // perform atomic increments
    await updateDoc(userRef, {
      totalWasteRecycled: increment(weightKg),
      totalCO2Saved: increment(co2Saved),
      carbonCredits: increment(carbonCreditsEarned),
    });

    // Optionally return transaction id -- not specified but could be used
    // return txRef.id;
  } catch (error) {
    console.error('Failed to record recycling transaction', error);
    throw error;
  }
}

// Helper to fetch the current impact stats for a user.  If the document
// does not exist, returns zeros.
export async function getUserImpactStats(
  userId: string,
): Promise<{totalWasteRecycled: number; totalCO2Saved: number; carbonCredits: number}> {
  if (!userId) {
    throw new Error('userId is required');
  }
  const userRef = doc(usersCol, userId);
  try {
    const snap = await getDoc(userRef);
    if (!snap.exists()) {
      return {
        totalWasteRecycled: 0,
        totalCO2Saved: 0,
        carbonCredits: 0,
      };
    }
    const data = snap.data();
    return {
      totalWasteRecycled: data.totalWasteRecycled || 0,
      totalCO2Saved: data.totalCO2Saved || 0,
      carbonCredits: data.carbonCredits || 0,
    };
  } catch (error) {
    console.error('Error fetching user impact stats', error);
    throw error;
  }
}
